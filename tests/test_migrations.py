"""The database built by Alembic migrations must match the models exactly."""

from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

ROOT = Path(__file__).resolve().parent.parent


def alembic_config(url):
    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT / "migrations"))
    cfg.attributes["url"] = url
    return cfg


def test_migrations_build_the_same_database_as_the_models(db_url):
    cfg = alembic_config(db_url)
    command.upgrade(cfg, "head")
    try:
        command.check(cfg)                 # raises if the models have changes no migration covers
    except AutogenerateDiffsDetected as e:  # pragma: no cover - the message lists what's missing
        pytest.fail(f"A model change has no migration: {e}")


def test_migrations_can_be_undone(db_url):
    cfg = alembic_config(db_url)
    command.upgrade(cfg, "head")
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")
